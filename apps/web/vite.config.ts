import adapter from "@sveltejs/adapter-node";
import { paraglideVitePlugin } from "@inlang/paraglide-js";
import { sveltekit } from "@sveltejs/kit/vite";
import { defineConfig, type ViteUserConfig } from "vite";
import { securityCspDirectives } from "./src/lib/security/csp.ts";
import {
  buildFlagDefines,
  FEATURE_FLAGS,
  flagDefineEnv,
  isDevServerRun,
} from "./src/lib/flags/registry.ts";
/**
 * SvelteKit 3 reads project configuration from this `sveltekit(...)` plugin
 * call — there is no separate svelte.config file. The API base URL the CSP
 * should bless comes from VITE_API_URL (same value the client bundle uses to
 * reach the housing API), defaulting to the local API dev server.
 */
const apiUrl = process.env.VITE_API_URL ?? "http://localhost:3000";

export default defineConfig(({ command, mode }) => {
  return {
    plugins: [
      sveltekit({
        adapter: adapter(),
        // Content Security Policy (documented `csp` config) — the value is
        // generated by src/lib/security/csp.ts and unit-tested there.
        // Inline scripts are a dev-server-only relaxation (HMR), keyed on
        // the same predicate as the feature flags: every build and preview
        // excludes `unsafe-inline`, whatever NODE_ENV says.
        csp: {
          mode: "auto",
          directives: securityCspDirectives({
            apiUrl,
            allowInlineScripts: isDevServerRun(command, mode),
          }),
        },
      }),
      paraglideVitePlugin({
        project: "./project.inlang",
        outdir: "./src/lib/paraglide",
        emitTsDeclarations: true,
        strategy: ["url", "cookie", "baseLocale"],
      }),
    ],
    // Flag machinery defines: `__DEV_SERVER__` marks a dev-server run, and
    // the per-flag `__FLAG_<SCREAMING_SNAKE>__` booleans are true only for
    // a dev-server run whose command time set VITE_FEATURE_<NAME>=1 (see
    // flagDefineEnv). Both are statically replaced in every build/preview
    // — whatever NODE_ENV or --mode is in effect — so flagged code and the
    // override machinery are stripped from built output. Empty registry
    // today.
    define: {
      __DEV_SERVER__: isDevServerRun(command, mode),
      ...buildFlagDefines(FEATURE_FLAGS, flagDefineEnv(command, mode, process.env)),
    },
    server: {
      port: 5173,
    },
    resolve: {
      alias: {
        // Node subpath-imports alias (#lib) declared in package.json
        // `imports`, mirrored here so Vitest entry points resolve
        // identically.
        "#lib": `${import.meta.dirname}/src/lib`,
      },
    },
  } satisfies ViteUserConfig;
});
